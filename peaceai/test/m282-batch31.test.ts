test("quansync forwards a thenable rejection handler, and a check that is not quansync is refused", () => {
  const source = text("qs-src-index.ts.txt");
  const next = forwardThenableRejection(source);
  assert.match(next ?? "", /then\(\.\.\.thenArgs\)/);
  assert.equal(forwardThenableRejection(next!), null);
  assert.equal(forwardThenableRejection(source.replaceAll("export function quansync", "export function kept")), null);
});

test("copy skips the __proto__ key, and a check that is not copy is refused", () => {
  const source = text("ca-src-index.ts.txt");
  const next = skipProtoKey(source);
  assert.match(next ?? "", /key === '__proto__'/);
  assert.equal(skipProtoKey(next!), null);
  assert.equal(skipProtoKey(source.replace("export function copy", "export function kept")), null);
});

test("$close stores the original error on cause, and a check that is not createBirpc is refused", () => {
  const source = text("bp-src-index.ts.txt");
  const next = closeSetsErrorCause(source);
  assert.match(next ?? "", /customError\.cause \?\?= error/);
  assert.equal(closeSetsErrorCause(next!), null);
  assert.equal(closeSetsErrorCause(source.replace("export function createBirpc", "export function kept")), null);
});

function rows() {
  const node = visibleNodeBin()!;
  const mods = runtime();
  return {
    mods,
    list: [
      {
        files: { ...filesOf("qs-"), "package.json": Buffer.from(PRIVATE_PKG), "vitest.config.cjs": Buffer.from(VITEST_CJS) },
        pattern: "^src/index\\.ts$",
        cmd: [node, "node_modules/vitest/vitest.mjs", "run", "--config", "vitest.config.cjs", "test/index.test.ts"],
        why: /async error/,
        restores: /then\(\.\.\.thenArgs\)/,
      },
      {
        files: { ...filesOf("ca-"), "package.json": Buffer.from(PRIVATE_PKG), "vitest.config.cjs": Buffer.from(VITEST_CJS) },
        pattern: "^src/index\\.ts$",
        cmd: [node, "node_modules/vitest/vitest.mjs", "run", "--config", "vitest.config.cjs", "test/index.test.ts"],
        why: /AssertionError|polluted|to be/,
        restores: /key === '__proto__'/,
      },
      {
        files: { ...filesOf("bp-"), "package.json": Buffer.from(PRIVATE_PKG), "vitest.config.cjs": Buffer.from(VITEST_CJS) },
        pattern: "^src/index\\.ts$",
        cmd: [node, "node_modules/vitest/vitest.mjs", "run", "--config", "vitest.config.cjs", "test/close.test.ts"],
        why: /TypeError|cause|Cannot read properties of undefined/,
        restores: /customError\.cause \?\?= error/,
      },
    ],
  };
}

test("the parent file fails the published check because the repair is absent, in-process and inside bwrap", (t) => {
  if (!practiceSandboxReady()) { t.skip("bwrap is not installed"); return; }
  const node = visibleNodeBin();
  assert.ok(node);
  const built = rows();
  for (const row of built.list) {
    const dir = mkdtempSync(join(tmpdir(), "m282-kill-"));
    placeFiles(dir, { ...row.files, ".gitignore": "node_modules\n" });
    symlinkSync(built.mods, join(dir, "node_modules"));
    gitInit(dir);
    const direct = spawnSync(row.cmd[0]!, row.cmd.slice(1), {
      cwd: dir, encoding: "utf8", timeout: 180_000, env: childEnv(),
    });
    const directOut = `${direct.stdout}\n${direct.stderr}`;
    assert.notEqual(direct.status, 0, directOut.slice(-1200));
    assert.match(directOut, row.why, directOut.slice(-1200));
    assert.doesNotMatch(directOut, /ReferenceError/, directOut.slice(-400));
    const sand = runInPracticeSandbox(dir, row.cmd, 180_000, { capture: true, nodePath: node, nodeModules: built.mods });
    assert.equal(sand.unsafe, false, sand.stdout.slice(-400));
    assert.notEqual(sand.code, 0, sand.stdout.slice(-1200));
    assert.match(sand.stdout, row.why, sand.stdout.slice(-1200));
    const repaired = repairBatch31({
      root: dir, output: directOut, sourcePattern: row.pattern, nodePath: node!, nodeModules: built.mods, testCommand: row.cmd,
    });
    assert.ok(repaired, directOut.slice(-1200));
    assert.match(repaired!.diff, row.restores);
    rmSync(dir, { recursive: true, force: true });
  }
});

test("an any-cast that only matches one recorded answer is test-only for each batch 31 family", (t) => {
  if (!practiceSandboxReady()) { t.skip("bwrap is not installed"); return; }
  const node = visibleNodeBin();
  assert.ok(node);
  for (const symbol of ["quansync", "copy", "createBirpc"]) {
    const strict = `export function ${symbol}(kind: string): string {\n  return kind === "b" ? "B" : "A";\n}\n`;
    const over = `export function ${symbol}(kind: any): string {\n  return "A";\n}\n`;
    const make = (body: string) => {
      const dir = mkdtempSync(join(tmpdir(), "m282-grade-"));
      mkdirSync(join(dir, "src"), { recursive: true });
      writeFileSync(join(dir, "src/fn.ts"), body);
      return dir;
    };
    const left = make(over);
    const right = make(strict);
    try {
      const graded = gradeBehavior({
        candidateRoot: left, fixRoot: right, nodePath: node!,
        target: { symbol, file: "src/fn.ts", form: "named", exportName: symbol, args: [["a"]] },
      });
      assert.equal(graded.behavior, "verified_test_only", symbol);
    } finally {
      rmSync(left, { recursive: true, force: true });
      rmSync(right, { recursive: true, force: true });
    }
  }
});

test("the published quansync, copy-anything, and birpc checks fail before the repair and pass after, inside the sandbox", (t) => {
  if (!practiceSandboxReady()) { t.skip("bwrap is not installed"); return; }
  const node = visibleNodeBin();
  assert.ok(node);
  const built = rows();
  for (const row of built.list) {
    const dir = mkdtempSync(join(tmpdir(), "m282-run-"));
    placeFiles(dir, { ...row.files, ".gitignore": "node_modules\n" });
    symlinkSync(built.mods, join(dir, "node_modules"));
    gitInit(dir);
    const before = runInPracticeSandbox(dir, row.cmd, 180_000, { capture: true, nodePath: node, nodeModules: built.mods });
    assert.equal(before.unsafe, false, before.stdout.slice(-400));
    assert.notEqual(before.code, 0, before.stdout.slice(-800));
    const repaired = repairBatch31({
      root: dir, output: before.stdout, sourcePattern: row.pattern, nodePath: node!, nodeModules: built.mods, testCommand: row.cmd,
    });
    assert.ok(repaired, before.stdout.slice(-1200));
    assert.match(repaired!.diff, row.restores);
    rmSync(dir, { recursive: true, force: true });
  }
});
