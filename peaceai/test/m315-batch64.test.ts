// Third-party bytes run only inside the practice sandbox.
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { cpSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import test from "node:test";
import { assignStringValueWithoutMergingAsObject, useRegexMatchCaptureForListLeadAndIndent, returnZeroForEmptyArraySum, repairBatch64 } from "../lib/batch64.ts";
