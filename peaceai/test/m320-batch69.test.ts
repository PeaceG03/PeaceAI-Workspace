test("map-files re-resolves glob results against cwd, and a check that is not that unresolved-cwd-glob shape is refused", () => {
  const source = text("mf-index.js.txt");
  const next = resolveGlobResultsAgainstCwd(source);
  assert.match(next ?? "", /relative\(path\.resolve\(cwd, filepath\)\)/);
  assert.equal(resolveGlobResultsAgainstCwd(next!), null);
  assert.equal(resolveGlobResultsAgainstCwd(source.replace(
    "  var files = glob.sync(patterns, options);\n\n  return files.reduce(function (cache, filepath) {\n    var key = name(filepath, options);",
    "  var files = glob.sync(patterns, options);\n\n  return files.reduce(function (cache, filepath) {\n    var key = name(filepath, options); ",
  )), null);
});

